import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, symlink, writeFile, rename, readFile, chmod } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import { createProjectLeaseProvider } from '../../src/providers/public/project_lease.mjs';
const run = promisify(execFile);
const fixtureRoot = fileURLToPath(new URL('../../../../.ans/runtime/legion-cli-role-owned-v2/DesktopEngineer/fixtures/', import.meta.url));
async function fixture(t) {
  await mkdir(fixtureRoot, { recursive: true });
  const root = await mkdtemp(join(fixtureRoot, 'lease-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const workspace = join(root, 'workspace');
  await mkdir(workspace);
  return { root, workspace, leaseRoot: join(root, 'private-leases') };
}
test('shared physical project lock rejects a second process independently of userData; release permits reacquisition', async (t) => {
  const f = await fixture(t);
  const provider = createProjectLeaseProvider({ leaseRoot: f.leaseRoot });
  t.after(() => provider.close());
  const acquired = await provider.acquire(f.workspace);
  assert.equal(acquired.ok, true);
  assert.equal((await provider.assertCurrent(acquired.value)).ok, true);
  const moduleUrl = new URL('../../src/providers/public/project_lease.mjs', import.meta.url).href;
  const script = `import {createProjectLeaseProvider} from ${JSON.stringify(moduleUrl)}; const p=createProjectLeaseProvider({leaseRoot:process.argv[1]}); const r=await p.acquire(process.argv[2]); console.log(JSON.stringify(r)); if(r.ok) await p.release(r.value); await p.close();`;
  const child = await run(process.execPath, ['--input-type=module', '-e', script, f.leaseRoot, f.workspace], { env: { PATH: process.env.PATH, LEGION_USER_DATA: join(f.root, 'other-user-data') } });
  assert.equal(JSON.parse(child.stdout).error.code, 'lease_busy');
  assert.equal((await provider.release(acquired.value)).ok, true);
  assert.equal((await provider.release(acquired.value)).ok, true);
  const next = await run(process.execPath, ['--input-type=module', '-e', script, f.leaseRoot, f.workspace], { env: { PATH: process.env.PATH } });
  assert.equal(JSON.parse(next.stdout).ok, true);
  assert.equal((await provider.close()).ok, true);
  assert.equal((await provider.close()).ok, true);
  assert.equal((await provider.acquire(f.workspace)).error.code, 'closed');
});
test('same workspace symlink alias contends for the same lease; forged handles have no authority', async (t) => {
  const f = await fixture(t);
  const first = createProjectLeaseProvider({ leaseRoot: f.leaseRoot });
  const second = createProjectLeaseProvider({ leaseRoot: f.leaseRoot });
  t.after(async () => { await first.close(); await second.close(); });
  const alias = join(f.root, 'alias');
  await symlink(f.workspace, alias);
  const acquired = await first.acquire(alias);
  assert.equal(acquired.ok, true);
  assert.equal((await second.acquire(f.workspace)).error.code, 'lease_busy');
  assert.equal((await second.assertCurrent(acquired.value)).error.code, 'lease_lost');
  assert.equal((await first.assertCurrent({ ...acquired.value })).error.code, 'lease_lost');
  assert.equal((await first.release(acquired.value)).ok, true);
});
test('physical workspace replacement and marker tampering revoke the lease and do not erase another lock', async (t) => {
  const f = await fixture(t);
  const provider = createProjectLeaseProvider({ leaseRoot: f.leaseRoot });
  const acquired = await provider.acquire(f.workspace);
  assert.equal(acquired.ok, true);
  await rename(f.workspace, join(f.root, 'original-workspace'));
  await mkdir(f.workspace);
  assert.equal((await provider.assertCurrent(acquired.value)).error.code, 'lease_lost');
  assert.equal((await provider.release(acquired.value)).error.code, 'lease_lost');
  assert.equal((await provider.close()).error.code, 'lease_lost');
  const second = createProjectLeaseProvider({ leaseRoot: f.leaseRoot });
  const fresh = await second.acquire(f.workspace);
  const key = createHash('sha256').update(`${fresh.value.workspace.deviceId}:${fresh.value.workspace.fileId}`).digest('hex');
  const marker = join(f.leaseRoot, key, 'holder');
  await writeFile(marker, 'foreign-lock');
  assert.equal((await second.assertCurrent(fresh.value)).error.code, 'lease_lost');
  assert.equal((await second.release(fresh.value)).error.code, 'lease_lost');
  assert.equal(await readFile(marker, 'utf8'), 'foreign-lock');
});
test('unsafe lease-root symlinks or public permissions fail closed; arbitrary userData options are rejected', async (t) => {
  const f = await fixture(t);
  const target = join(f.root, 'target');
  await mkdir(target, { mode: 0o700 });
  const linked = join(f.root, 'linked');
  await symlink(target, linked);
  const provider = createProjectLeaseProvider({ leaseRoot: linked });
  assert.equal((await provider.acquire(f.workspace)).error.code, 'lease_unavailable');
  await provider.close();
  await chmod(target, 0o755);
  const publicRoot = createProjectLeaseProvider({ leaseRoot: target });
  assert.equal((await publicRoot.acquire(f.workspace)).error.code, 'lease_unavailable');
  await publicRoot.close();
  assert.throws(() => createProjectLeaseProvider({ userDataDir: f.root }));
  const source = await readFile(new URL('../../src/providers/impl/project_lease.mjs', import.meta.url), 'utf8');
  assert.match(source, /homedir\(\), '\.legion-project-leases'/u);
  assert.equal(/userDataDir|process\.env/u.test(source), false);
});
